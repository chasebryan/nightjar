#!/usr/bin/env python3
"""Generate the Swift and Kotlin trace-parity tests from fixtures.json.

fixtures.json holds the behavior the Swift (Trace.swift) and
Kotlin (Trace.kt) implementations of TraceRule + TraceAnalyzer
AGREE on — every expectation in it was derived by hand from the
two sources, with signatures computed by hashlib over the exact
bytes. One shared expectation set, two generated test files, so
the implementations can't silently drift apart: change the
behavior in one, and the other's generated test is the spec it
must still meet.

Run:  python3 gen_fixtures.py
Outputs:
  ios/nightjarTests/TraceParityTests.swift        (in this repo)
  <android>/app/src/test/java/net/nosuchmachine/nightjarhack/TraceParityTest.kt
"""
import json
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
HACK = HERE.parents[1]                      # ~/workspace/njh-work/hack
ANDROID = Path(os.environ.get(
    "NIGHTJAR_ANDROID_TREE",
    Path.home() / "workspace/nightjar-hack-android"))

FIXTURES = json.loads((HERE / "fixtures.json").read_text())


def camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("-"))


def swift_escape(s: str) -> str:
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\r", "\\r").replace("\n", "\\n")
             .replace("\t", "\\t"))


def kotlin_escape(s: str) -> str:
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("$", "\\$")
             .replace("\r", "\\r").replace("\n", "\\n")
             .replace("\t", "\\t"))


# ---------------------------------------------------------------- Swift

def gen_swift() -> str:
    out = []
    out.append("""import XCTest
@testable import nightjar

/// Cross-platform parity fixtures — GENERATED by
/// tools/parity/gen_fixtures.py from tools/parity/fixtures.json.
/// Do not edit by hand; edit the fixtures and regenerate.
///
/// Every case here is behavior the Kotlin twin (Trace.kt)
/// implements identically: rule parsing/matching, reply
/// signatures, first lines, service hints, and reference
/// extraction. If one of these fails, one of the two
/// implementations drifted — the fixture is the contract.
final class TraceParityTests: XCTestCase {
""")
    for case in FIXTURES["ruleCases"]:
        name = camel(case["name"])
        out.append(f"    // MARK: Rule case — {case['name']}\n")
        out.append(f"    func testRule{name}() {{")
        out.append(f'        let rules = TraceRule.parse('
                   f'"{swift_escape(case["input"])}")')
        exp = case["expected"]
        out.append(f"        XCTAssertEqual(rules.count, {len(exp)})")
        for i, rule in enumerate(exp):
            m, a = rule["matcher"], rule["action"]
            if "contains" in m:
                out.append(
                    f"        guard case .contains(let needle{i})"
                    f" = rules[{i}].matcher"
                    f' else {{ return XCTFail("rule {i}: not contains") }}')
                out.append(
                    f'        XCTAssertEqual(needle{i}, '
                    f'"{swift_escape(m["contains"])}")')
            else:
                out.append(
                    f"        guard case .port(let port{i})"
                    f" = rules[{i}].matcher"
                    f' else {{ return XCTFail("rule {i}: not port") }}')
                out.append(
                    f"        XCTAssertEqual(port{i}, {m['port']})")
            if "followup" in a:
                out.append(
                    f"        guard case .followup(let name{i})"
                    f" = rules[{i}].action"
                    f' else {{ return XCTFail("rule {i}: not followup") }}')
                out.append(
                    f'        XCTAssertEqual(name{i}, '
                    f'"{swift_escape(a["followup"])}")')
            elif "tag" in a:
                out.append(
                    f"        guard case .tag(let label{i})"
                    f" = rules[{i}].action"
                    f' else {{ return XCTFail("rule {i}: not tag") }}')
                out.append(
                    f'        XCTAssertEqual(label{i}, '
                    f'"{swift_escape(a["tag"])}")')
            else:
                out.append(
                    f"        guard case .stop = rules[{i}].action"
                    f' else {{ return XCTFail("rule {i}: not stop") }}')
        for mt in case.get("matchTests", []):
            for i, want in enumerate(mt["matches"]):
                out.append(
                    f"        XCTAssertEqual(rules[{i}].matches("
                    f'text: "{swift_escape(mt["text"])}", '
                    f"port: {mt['port']}), "
                    f"{'true' if want else 'false'})")
        out.append("    }\n")
    for case in FIXTURES["analyzeCases"]:
        name = camel(case["name"])
        exp = case["expected"]
        out.append(f"    // MARK: Analyze case — {case['name']}\n")
        out.append(f"    func testAnalyze{name}() {{")
        out.append(
            f'        let data = Data("{swift_escape(case["dataText"])}"'
            f'.utf8)')
        out.append(
            f"        let a = TraceAnalyzer.analyze(data: data, "
            f'host: "{case["host"]}", port: {case["port"]})')
        out.append(
            f'        XCTAssertEqual(a.signature, '
            f'"{exp["signature"]}")')
        out.append(
            f'        XCTAssertEqual(a.firstLine, '
            f'"{swift_escape(exp["firstLine"])}")')
        if exp["serviceHint"] is None:
            out.append("        XCTAssertNil(a.serviceHint)")
        else:
            out.append(
                f'        XCTAssertEqual(a.serviceHint, '
                f'"{swift_escape(exp["serviceHint"])}")')
        out.append(
            f"        XCTAssertEqual(a.references.count, "
            f"{len(exp['references'])})")
        for i, ref in enumerate(exp["references"]):
            out.append(
                f'        XCTAssertEqual(a.references[{i}].host, '
                f'"{swift_escape(ref["host"])}")')
            if ref["port"] is None:
                out.append(
                    f"        XCTAssertNil(a.references[{i}].port)")
            else:
                out.append(
                    f"        XCTAssertEqual(a.references[{i}].port, "
                    f"{ref['port']})")
        out.append("    }\n")
    out.append("}")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- Kotlin

def gen_kotlin() -> str:
    out = []
    out.append("""package net.nosuchmachine.nightjarhack

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/// Cross-platform parity fixtures — GENERATED by
/// tools/parity/gen_fixtures.py from tools/parity/fixtures.json.
/// Do not edit by hand; edit the fixtures and regenerate.
///
/// Every case here is behavior the Swift twin (Trace.swift)
/// implements identically: rule parsing/matching, reply
/// signatures, first lines, service hints, and reference
/// extraction. If one of these fails, one of the two
/// implementations drifted — the fixture is the contract.
class TraceParityTest {
""")
    for case in FIXTURES["ruleCases"]:
        name = camel(case["name"])
        out.append(f"    // Rule case — {case['name']}")
        out.append(f"    @Test fun rule{name}() {{")
        out.append(f'        val rules = TraceRule.parse('
                   f'"{kotlin_escape(case["input"])}")')
        exp = case["expected"]
        out.append(f"        assertEquals({len(exp)}, rules.size)")
        for i, rule in enumerate(exp):
            m, a = rule["matcher"], rule["action"]
            if "contains" in m:
                out.append(
                    f'        assertEquals("{kotlin_escape(m["contains"])}"'
                    f", rules[{i}].matchText)")
                out.append(f"        assertNull(rules[{i}].matchPort)")
            else:
                out.append(
                    f"        assertEquals({m['port']}, "
                    f"rules[{i}].matchPort)")
                out.append(f"        assertNull(rules[{i}].matchText)")
            if "followup" in a:
                out.append(
                    f"        assertEquals(TraceRule.Action.FOLLOWUP, "
                    f"rules[{i}].action)")
                out.append(
                    f'        assertEquals('
                    f'"{kotlin_escape(a["followup"])}", '
                    f"rules[{i}].actionValue)")
            elif "tag" in a:
                out.append(
                    f"        assertEquals(TraceRule.Action.TAG, "
                    f"rules[{i}].action)")
                out.append(
                    f'        assertEquals("{kotlin_escape(a["tag"])}", '
                    f"rules[{i}].actionValue)")
            else:
                out.append(
                    f"        assertEquals(TraceRule.Action.STOP, "
                    f"rules[{i}].action)")
                out.append(
                    f'        assertEquals("", rules[{i}].actionValue)')
        for mt in case.get("matchTests", []):
            for i, want in enumerate(mt["matches"]):
                out.append(
                    f"        assertEquals({str(want).lower()}, "
                    f"rules[{i}].matches({mt['port']}, "
                    f'"{kotlin_escape(mt["text"])}".lowercase()))')
        out.append("    }\n")
    for case in FIXTURES["analyzeCases"]:
        name = camel(case["name"])
        exp = case["expected"]
        out.append(f"    // Analyze case — {case['name']}")
        out.append(f"    @Test fun analyze{name}() {{")
        out.append(
            f'        val a = TraceAnalyzer.analyze('
            f'"{kotlin_escape(case["dataText"])}"'
            f".toByteArray(Charsets.UTF_8), "
            f'"{case["host"]}", {case["port"]})')
        out.append(
            f'        assertEquals("{exp["signature"]}", a.signature)')
        out.append(
            f'        assertEquals('
            f'"{kotlin_escape(exp["firstLine"])}", a.firstLine)')
        if exp["serviceHint"] is None:
            out.append("        assertNull(a.serviceHint)")
        else:
            out.append(
                f'        assertEquals('
                f'"{kotlin_escape(exp["serviceHint"])}", a.serviceHint)')
        out.append(
            f"        assertEquals({len(exp['references'])}, "
            f"a.references.size)")
        for i, ref in enumerate(exp["references"]):
            out.append(
                f'        assertEquals("{kotlin_escape(ref["host"])}", '
                f"a.references[{i}].host)")
            if ref["port"] is None:
                out.append(f"        assertNull(a.references[{i}].port)")
            else:
                out.append(
                    f"        assertEquals({ref['port']}, "
                    f"a.references[{i}].port)")
        out.append("    }\n")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> None:
    swift_path = HACK / "ios/nightjarTests/TraceParityTests.swift"
    kotlin_path = (ANDROID / "app/src/test/java/net/nosuchmachine/"
                   "nightjarhack/TraceParityTest.kt")
    kotlin_path.parent.mkdir(parents=True, exist_ok=True)
    swift_path.write_text(gen_swift())
    kotlin_path.write_text(gen_kotlin())
    print("wrote", swift_path)
    print("wrote", kotlin_path)


if __name__ == "__main__":
    main()
