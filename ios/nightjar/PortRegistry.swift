/// The global port-service registry: the
/// nmap services list (the IANA assignments
/// as the scanning world maintains them) —
/// every named TCP and UDP service, so a
/// port found open on the wire can be named
/// even when no probe in the library speaks
/// its language. 12,093 entries, generated
/// 2026-10-18 from nmap's nmap-services.
/// Do not hand-edit — regenerate from the
/// source list. The house's curated names
/// in ScanModel.serviceNames still outrank
/// these wherever both exist.
///
/// Stored as packed text: bare port keys
/// are TCP, port+"u" keys are UDP. One
/// parse, once, like the house's other
/// registries.
enum PortRegistry {

    static let names: [String: String] = {
        var out: [String: String] = [:]
        out.reserveCapacity(12500)
        for chunk in chunks {
            for line in chunk.split(
                    separator: "\n") {
                let parts = line.split(
                    separator: "\t",
                    maxSplits: 1)
                guard parts.count == 2
                else { continue }
                out[String(parts[0])] =
                    String(parts[1])
            }
        }
        return out
    }()

    /// A port's registry name, by protocol.
    static func name(_ port: Int,
                     udp: Bool = false)
        -> String? {
        names["\(port)\(udp ? "u" : "")"]
